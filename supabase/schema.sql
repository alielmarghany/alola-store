create function admin_analytics() returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_today date := (now() at time zone 'Africa/Cairo')::date;
  v_month date := date_trunc('month', v_today)::date;
  v_last date := (v_month - interval '1 month')::date;
  v_last_same date := least(v_last + (extract(day from v_today)::int - 1), v_month - 1);
  v_avg numeric;
  t record; y record; m record; lm record;
begin
  perform require_admin();
  select coalesce(sum(total), 0) revenue, count(*) orders into t from orders where status <> 'cancelled' and local_day = v_today;
  select coalesce(sum(total), 0) revenue into y from orders where status <> 'cancelled' and local_day = v_today - 1;
  select coalesce(sum(total), 0) revenue, count(*) orders into m from orders where status <> 'cancelled' and local_day between v_month and v_today;
  select coalesce(sum(total), 0) revenue into lm from orders where status <> 'cancelled' and local_day between v_last and v_last_same;
  v_avg := case when m.orders > 0 then round(m.revenue::numeric / m.orders) else 0 end;

  return jsonb_build_object(
    'today', jsonb_build_object('revenue', t.revenue, 'orders', t.orders, 'yesterdayRevenue', y.revenue),
    'month', jsonb_build_object('revenue', m.revenue, 'orders', m.orders, 'lastMonthSamePeriod', lm.revenue, 'aov', v_avg),
    'clients', jsonb_build_object('total', (select count(*) from customers), 'newThisMonth', (select count(*) from customers where local_day >= v_month)),
    'daily', (select jsonb_agg(jsonb_build_object('key', to_char(d, 'YYYY-MM-DD'), 'revenue', coalesce(r.revenue, 0), 'orders', coalesce(r.orders, 0)) order by d)
      from generate_series(v_today - 89, v_today, interval '1 day') d
      left join (select local_day, sum(total) revenue, count(*) orders from orders where status <> 'cancelled' group by 1) r on r.local_day = d::date),
    'monthly', (select jsonb_agg(jsonb_build_object('key', to_char(d, 'YYYY-MM'), 'revenue', coalesce(r.revenue, 0), 'orders', coalesce(r.orders, 0)) order by d)
      from generate_series(v_month - interval '11 months', v_month, interval '1 month') d
      left join (select date_trunc('month', local_day::timestamp) mth, sum(total) revenue, count(*) orders from orders where status <> 'cancelled' group by 1) r on r.mth = d),
    'statusCounts', (select jsonb_object_agg(s, (select count(*) from orders o where o.status = s)) from unnest(array['pending','confirmed','shipped','delivered','cancelled']) s),
    'topProducts', coalesce((select jsonb_agg(x order by x.revenue desc) from (
      select i.name, i.brand, sum(i.qty) qty, sum(i.qty * i.price) revenue from order_items i join orders o on o.id = i.order_id
      where o.status <> 'cancelled' and o.local_day >= v_today - 29 group by i.name, i.brand order by 4 desc limit 5) x), '[]'),
    'lowStock', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'stock', stock) order by stock) from products where active and stock <= 10), '[]'),
    'recentOrders', coalesce((select jsonb_agg(order_json(o) order by o.id desc) from (select * from orders order by id desc limit 6) o), '[]')
  );
end $$;

create function admin_set_theme(p_theme text) returns text language plpgsql security definer set search_path = public as $$
begin
  perform require_admin();
  if p_theme not in ('default','newyear','halloween','ramadan','eid') then raise exception 'Unknown theme'; end if;
  update store_settings set theme = p_theme where id; -- Supabase refuses updates without a where clause
  return p_theme;
end $$;

create function admin_list_products() returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform require_admin();
  return coalesce((select jsonb_agg(to_jsonb(p) || jsonb_build_object('sold', coalesce((
      select sum(i.qty) from order_items i join orders o on o.id = i.order_id where i.product_id = p.id and o.status <> 'cancelled'), 0)) order by p.id desc)
    from products p), '[]');
end $$;

create function admin_list_orders(p_q text default '', p_status text default '', p_page integer default 1) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_size constant integer := 20;
  v_q text := left(btrim(coalesce(p_q, '')), 80);
  v_like text := like_pattern(v_q);
  v_num bigint := null;
  v_digits text;
  v_total bigint;
  v_rows jsonb;
begin
  perform require_admin();
  v_digits := (regexp_match(v_q, '^(?:alo-?)?([0-9]{1,15})$', 'i'))[1];
  if v_digits is not null then
    v_num := v_digits::bigint - case when char_length(v_digits) >= 5 then 10000 else 0 end;
  end if;

  select count(*) into v_total from orders o
  where (coalesce(p_status, '') = '' or o.status = p_status)
    and (v_q = '' or o.customer_name ilike v_like or o.email ilike v_like or o.phone ilike v_like or o.id = v_num);

  select coalesce(jsonb_agg(order_json(o) || jsonb_build_object('item_count', (select sum(qty) from order_items where order_id = o.id)) order by o.id desc), '[]') into v_rows
  from (select * from orders o
    where (coalesce(p_status, '') = '' or o.status = p_status)
      and (v_q = '' or o.customer_name ilike v_like or o.email ilike v_like or o.phone ilike v_like or o.id = v_num)
    order by o.id desc limit v_size offset (greatest(p_page, 1) - 1) * v_size) o;

  return jsonb_build_object('total', v_total, 'page', greatest(p_page, 1), 'size', v_size, 'rows', v_rows);
end $$;

create function admin_get_order(p_id bigint) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare o orders;
begin
  perform require_admin();
  select * into o from orders where id = p_id;
  if not found then raise exception 'Order not found'; end if;
  return order_json(o) || jsonb_build_object('items', (select jsonb_agg(jsonb_build_object('product_id', product_id, 'name', name, 'brand', brand, 'price', price, 'qty', qty) order by id) from order_items where order_id = p_id));
end $$;

create function admin_set_order_status(p_id bigint, p_status text) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  o orders;
  it record;
begin
  perform require_admin();
  if p_status not in ('pending','confirmed','shipped','delivered','cancelled') then raise exception 'Invalid status'; end if;
  select * into o from orders where id = p_id for update;
  if not found then raise exception 'Order not found'; end if;
  if o.status <> p_status then
    -- Cancelling puts the items back on the shelf; reopening takes them again.
    for it in select i.product_id, i.qty, i.name from order_items i where i.order_id = p_id and i.product_id is not null order by i.product_id loop
      if p_status = 'cancelled' then
        update products set stock = stock + it.qty where id = it.product_id;
      elsif o.status = 'cancelled' then
        update products set stock = stock - it.qty where id = it.product_id and stock >= it.qty;
        if not found then raise exception 'Not enough stock of % to reopen this order', it.name; end if;
      end if;
    end loop;
    update orders set status = p_status where id = p_id;
  end if;
  return admin_get_order(p_id);
end $$;

create function admin_list_customers(p_q text default '', p_sort text default 'recent', p_page integer default 1) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_size constant integer := 20;
  v_q text := left(btrim(coalesce(p_q, '')), 80);
  v_like text := like_pattern(v_q);
  v_total bigint;
  v_rows jsonb;
begin
  perform require_admin();
  select count(*) into v_total from customers c
  where v_q = '' or c.name ilike v_like or c.email ilike v_like or c.phone ilike v_like or c.city ilike v_like;

  select coalesce(jsonb_agg(to_jsonb(x)), '[]') into v_rows from (
    select c.*, count(o.id) filter (where o.status <> 'cancelled') order_count,
      coalesce(sum(o.total) filter (where o.status <> 'cancelled'), 0) total_spent, max(o.created_at) last_order
    from customers c left join orders o on o.customer_id = c.id
    where v_q = '' or c.name ilike v_like or c.email ilike v_like or c.phone ilike v_like or c.city ilike v_like
    group by c.id
    order by
      case when p_sort = 'spent' then coalesce(sum(o.total) filter (where o.status <> 'cancelled'), 0) end desc nulls last,
      case when p_sort = 'orders' then count(o.id) filter (where o.status <> 'cancelled') end desc nulls last,
      case when p_sort = 'name' then lower(c.name) end asc nulls last,
      max(o.created_at) desc nulls last, c.id desc
    limit v_size offset (greatest(p_page, 1) - 1) * v_size) x;

  return jsonb_build_object('total', v_total, 'page', greatest(p_page, 1), 'size', v_size, 'rows', v_rows);
end $$;

create function admin_get_customer(p_id bigint) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare c record;
begin
  perform require_admin();
  select cu.*, count(o.id) filter (where o.status <> 'cancelled') order_count,
    coalesce(sum(o.total) filter (where o.status <> 'cancelled'), 0) total_spent, max(o.created_at) last_order
  into c from customers cu left join orders o on o.customer_id = cu.id where cu.id = p_id group by cu.id;
  if not found then raise exception 'Customer not found'; end if;
  return to_jsonb(c) || jsonb_build_object('orders', coalesce((select jsonb_agg(order_json(o) || jsonb_build_object('item_count', (select sum(qty) from order_items where order_id = o.id)) order by o.id desc) from orders o where o.customer_id = p_id), '[]'));
end $$;

