-- Alola store: database schema, security rules and business logic for Supabase.
-- Run once on a new Supabase project (SQL editor), then optionally run seed.sql.
--
-- Security model: the browser only ever holds the public "anon" key, so everything is
-- enforced here. Shoppers can read live products and call place_order / subscribe.
-- Customers and orders have no table access at all; admins reach them through functions
-- that start by checking the caller is listed in the admins table.

-- ---------------------------------------------------------------- tables
create table products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 120),
  name_ar text not null default '' check (char_length(name_ar) <= 120),
  description_ar text not null default '' check (char_length(description_ar) <= 4000),
  how_to_ar text not null default '' check (char_length(how_to_ar) <= 2000),
  brand text not null check (char_length(brand) between 2 and 60),
  category text not null check (category in ('Skincare','Makeup','Hair','Fragrance')),
  price integer not null check (price > 0),
  compare_at integer,
  stock integer not null default 0 check (stock >= 0),
  description text not null default '' check (char_length(description) <= 4000),
  how_to text not null default '' check (char_length(how_to) <= 2000),
  ingredients text not null default '' check (char_length(ingredients) <= 2000),
  art text not null default 'bottle' check (art in ('dropper','pump','tube','jar','lipstick','mascara','perfume','bottle')),
  color text not null default 'cream' check (color in ('cream','white','olive','rose','amber','gold','ink','sky','plum')),
  image text check (image ~ '^https://'),
  tag text not null default '' check (char_length(tag) <= 20),
  featured boolean not null default false,
  active boolean not null default true,
  rating numeric(2,1),
  rating_count integer not null default 0,
  created_at timestamptz not null default now(),
  constraint compare_above_price check (compare_at is null or compare_at > price)
);

create table customers (
  id bigint generated by default as identity primary key,
  name text not null, email text not null unique, phone text not null,
  city text not null, address text not null,
  created_at timestamptz not null default now(),
  local_day date generated always as ((created_at at time zone 'Africa/Cairo')::date) stored
);

create table orders (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references customers(id),
  customer_name text not null, email text not null, phone text not null,
  city text not null, address text not null, notes text not null default '',
  subtotal integer not null, shipping integer not null, total integer not null,
  status text not null default 'pending' check (status in ('pending','confirmed','shipped','delivered','cancelled')),
  payment text not null default 'cod',
  user_id uuid references auth.users(id) on delete set null, -- the customer account, if logged in
  created_at timestamptz not null default now(),
  -- "Revenue per day" follows Cairo days, wherever the database runs.
  local_day date generated always as ((created_at at time zone 'Africa/Cairo')::date) stored
);
create index orders_day_idx on orders(local_day);
create index orders_customer_idx on orders(customer_id);
create index orders_user_idx on orders(user_id);

-- Details a logged-in customer saved for checkout. Only ever changed by that customer.
-- Orders link to accounts by login, never by matching an email address, so nobody can
-- see someone else's orders by signing up with their email.
create table customer_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '' check (char_length(name) <= 80),
  phone text not null default '' check (char_length(phone) <= 20),
  city text not null default '' check (char_length(city) <= 60),
  address text not null default '' check (char_length(address) <= 300),
  updated_at timestamptz not null default now()
);

create table order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references orders(id) on delete cascade,
  product_id bigint references products(id) on delete set null, -- orders keep their own copy of name and price
  name text not null, brand text not null, price integer not null, qty integer not null
);
create index order_items_order_idx on order_items(order_id);
create index order_items_product_idx on order_items(product_id);

create table notifications (
  id bigint generated by default as identity primary key,
  type text not null, title text not null, body text not null,
  order_id bigint references orders(id) on delete cascade,
  read boolean not null default false,
  created_at timestamptz not null default now()
);

create table subscribers (email text primary key, created_at timestamptz not null default now());
create table order_attempts (ip_hash text not null, at timestamptz not null default now());
create index order_attempts_idx on order_attempts(ip_hash, at);
create table admins (user_id uuid primary key);

create table store_settings (
  id boolean primary key default true check (id), -- single row
  shipping_fee integer not null default 60,
  free_shipping_over integer not null default 1000,
  theme text not null default 'default' check (theme in ('default','newyear','halloween','ramadan','eid'))
);
insert into store_settings default values;

-- ---------------------------------------------------------------- helpers
create function is_admin() returns boolean language sql stable security definer set search_path = public as
$$ select exists (select 1 from admins where user_id = auth.uid()) $$;

create function require_admin() returns void language plpgsql stable security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'Not authorised' using errcode = '42501'; end if;
end $$;

create function order_number(p_id bigint) returns text language sql immutable set search_path = public as
$$ select 'ALO-' || (10000 + p_id) $$;

create function order_json(o orders) returns jsonb language sql stable set search_path = public as
$$ select to_jsonb(o) || jsonb_build_object('number', order_number(o.id)) $$;

create function like_pattern(q text) returns text language sql immutable set search_path = public as
$$ select '%' || regexp_replace(q, '([%_\\])', '\\\1', 'g') || '%' $$;

-- ---------------------------------------------------------------- public functions
create function place_order(payload jsonb) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_name text := left(btrim(coalesce(payload->>'name', '')), 80);
  v_phone text := left(btrim(coalesce(payload->>'phone', '')), 20);
  v_email text := lower(left(btrim(coalesce(payload->>'email', '')), 120));
  v_city text := left(btrim(coalesce(payload->>'city', '')), 60);
  v_address text := left(btrim(coalesce(payload->>'address', '')), 300);
  v_notes text := left(btrim(coalesce(payload->>'notes', '')), 500);
  v_fields jsonb := '{}';
  v_ip text;
  v_item jsonb;
  v_line record;
  v_product products;
  v_lines jsonb := '[]';
  v_subtotal integer := 0;
  v_count integer := 0;
  v_shipping integer;
  v_total integer;
  v_settings store_settings;
  v_customer bigint;
  v_order bigint;
  v_user uuid := auth.uid();
begin
  -- Logged-in orders always use the account's own email.
  if v_user is not null then select lower(email) into v_email from auth.users where id = v_user; end if;

  -- A simple per-visitor limit, so a script can't flood the store with orders.
  v_ip := md5(coalesce(split_part(nullif(current_setting('request.headers', true), '')::json->>'x-forwarded-for', ',', 1), 'unknown'));
  delete from order_attempts where at < now() - interval '1 minute';
  if (select count(*) from order_attempts where ip_hash = v_ip) >= 20 then
    raise exception 'Too many orders. Please wait a minute and try again.';
  end if;
  insert into order_attempts (ip_hash) values (v_ip);

  if char_length(v_name) < 2 then v_fields := v_fields || '{"name":"Please enter your full name"}'; end if;
  if v_phone !~ '^\+?[0-9][0-9 ()-]{6,18}$' then v_fields := v_fields || '{"phone":"Please enter a valid phone number"}'; end if;
  if v_email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' then v_fields := v_fields || '{"email":"Please enter a valid email"}'; end if;
  if char_length(v_city) < 2 then v_fields := v_fields || '{"city":"Please choose your governorate"}'; end if;
  if char_length(v_address) < 5 then v_fields := v_fields || '{"address":"Please enter your full address"}'; end if;
  if v_fields <> '{}' then raise exception 'Please check your details' using detail = v_fields::text; end if;

  if jsonb_typeof(payload->'items') <> 'array' or jsonb_array_length(payload->'items') not between 1 and 50 then
    raise exception 'Your cart is empty';
  end if;
  for v_item in select value from jsonb_array_elements(payload->'items') loop
    if coalesce(v_item->>'id', '') !~ '^[0-9]{1,15}$' or coalesce(v_item->>'qty', '') !~ '^[0-9]{1,2}$' or (v_item->>'qty')::int < 1 then
      raise exception 'Invalid item in cart';
    end if;
  end loop;

  -- Always the database's prices, never the browser's. Rows are locked so two
  -- customers can't both buy the last unit.
  for v_line in
    select (value->>'id')::bigint as id, sum((value->>'qty')::int)::int as qty
    from jsonb_array_elements(payload->'items') group by 1 order by 1
  loop
    select * into v_product from products where id = v_line.id and active for update;
    if not found then raise exception 'An item in your cart is no longer available'; end if;
    if v_product.stock < v_line.qty then
      if v_product.stock > 0 then raise exception 'Only % left of %', v_product.stock, v_product.name;
      else raise exception '% just sold out', v_product.name; end if;
    end if;
    v_subtotal := v_subtotal + v_product.price * v_line.qty;
    v_count := v_count + v_line.qty;
    v_lines := v_lines || jsonb_build_object('id', v_product.id, 'name', v_product.name, 'brand', v_product.brand, 'price', v_product.price, 'qty', v_line.qty);
    update products set stock = stock - v_line.qty where id = v_line.id;
  end loop;

  select * into v_settings from store_settings;
  v_shipping := case when v_subtotal >= v_settings.free_shipping_over then 0 else v_settings.shipping_fee end;
  v_total := v_subtotal + v_shipping;

  insert into customers (name, email, phone, city, address) values (v_name, v_email, v_phone, v_city, v_address)
  on conflict (email) do update set name = excluded.name, phone = excluded.phone, city = excluded.city, address = excluded.address
  returning id into v_customer;

  insert into orders (customer_id, customer_name, email, phone, city, address, notes, subtotal, shipping, total, user_id)
  values (v_customer, v_name, v_email, v_phone, v_city, v_address, v_notes, v_subtotal, v_shipping, v_total, v_user)
  returning id into v_order;

  insert into order_items (order_id, product_id, name, brand, price, qty)
  select v_order, (l->>'id')::bigint, l->>'name', l->>'brand', (l->>'price')::int, (l->>'qty')::int from jsonb_array_elements(v_lines) l;

  -- The dashboard listens for new rows here through Supabase Realtime.
  insert into notifications (type, title, body, order_id)
  values ('order', 'New order ' || order_number(v_order),
    v_name || ' · ' || v_count || case when v_count = 1 then ' item' else ' items' end || ' · ' || to_char(v_total, 'FM999,999,990') || ' EGP', v_order);

  if v_user is not null and payload->>'save' = 'true' then
    insert into customer_profiles (user_id, name, phone, city, address) values (v_user, v_name, v_phone, v_city, v_address)
    on conflict (user_id) do update set name = excluded.name, phone = excluded.phone, city = excluded.city, address = excluded.address, updated_at = now();
  end if;

  return jsonb_build_object('number', order_number(v_order), 'total', v_total, 'subtotal', v_subtotal, 'shipping', v_shipping,
    'name', v_name, 'city', v_city, 'items', v_lines);
end $$;

-- A logged-in customer's own orders, newest first.
create function my_orders() returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'number', order_number(o.id), 'created_at', o.created_at, 'status', o.status, 'city', o.city,
    'subtotal', o.subtotal, 'shipping', o.shipping, 'total', o.total,
    'items', (select jsonb_agg(jsonb_build_object('name', i.name, 'name_ar', p.name_ar, 'brand', i.brand, 'price', i.price, 'qty', i.qty) order by i.id) from order_items i left join products p on p.id = i.product_id where i.order_id = o.id)
  ) order by o.id desc), '[]')
  from (select * from orders where user_id = auth.uid() order by id desc limit 100) o
$$;

create function subscribe(p_email text) returns void language plpgsql security definer set search_path = public as $$
declare v_email text := lower(left(btrim(coalesce(p_email, '')), 120));
begin
  if v_email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' then raise exception 'Please enter a valid email'; end if;
  insert into subscribers (email) values (v_email) on conflict do nothing;
end $$;

