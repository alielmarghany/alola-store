-- Alola store: database schema, security rules and business logic for Supabase.
-- Run once on a new Supabase project (SQL editor), then optionally run seed.sql.
--
-- Security model: the browser only ever holds the public "anon" key, so everything is
-- enforced here. Shoppers can read live products and call place_order / subscribe.
-- Customers and orders have no table access at all; admins reach them through functions
-- that start by checking the caller is listed in the admins table.

-- ---------------------------------------------------------------- tables
create table products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 120),
  code text unique check (code is null or char_length(code) between 1 and 40), -- the shop's own product code
  name_ar text not null default '' check (char_length(name_ar) <= 120),
  description_ar text not null default '' check (char_length(description_ar) <= 4000),
  how_to_ar text not null default '' check (char_length(how_to_ar) <= 2000),
  brand text not null check (char_length(brand) between 2 and 60),
  category text not null check (category in ('Skincare','Makeup','Hair','Fragrance')),
  price integer not null check (price > 0),
  compare_at integer,
  stock integer not null default 0 check (stock >= 0),
  description text not null default '' check (char_length(description) <= 4000),
  how_to text not null default '' check (char_length(how_to) <= 2000),
  ingredients text not null default '' check (char_length(ingredients) <= 2000),
  art text not null default 'bottle' check (art in ('dropper','pump','tube','jar','lipstick','mascara','perfume','bottle')),
  color text not null default 'cream' check (color in ('cream','white','olive','rose','amber','gold','ink','sky','plum')),
  image text check (image ~ '^https://'),
  tag text not null default '' check (char_length(tag) <= 20),
  featured boolean not null default false,
  active boolean not null default true,
  rating numeric(2,1),
  rating_count integer not null default 0,
  created_at timestamptz not null default now(),
  constraint compare_above_price check (compare_at is null or compare_at > price)
);

create table customers (
  id bigint generated by default as identity primary key,
  name text not null, email text not null unique, phone text not null,
  city text not null, address text not null,
  created_at timestamptz not null default now(),
  local_day date generated always as ((created_at at time zone 'Africa/Cairo')::date) stored
);

create table orders (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references customers(id),
  customer_name text not null, email text not null, phone text not null,
  city text not null, address text not null, notes text not null default '',
  subtotal integer not null, shipping integer not null, total integer not null,
  status text not null default 'pending' check (status in ('pending','confirmed','shipped','delivered','cancelled')),
  payment text not null default 'cod',
  user_id uuid references auth.users(id) on delete set null, -- the customer account, if logged in
  discount integer not null default 0 check (discount >= 0),
  discount_code text,
  created_at timestamptz not null default now(),
  -- "Revenue per day" follows Cairo days, wherever the database runs.
  local_day date generated always as ((created_at at time zone 'Africa/Cairo')::date) stored
);
create index orders_day_idx on orders(local_day);
create index orders_customer_idx on orders(customer_id);
create index orders_user_idx on orders(user_id);

-- Discount codes: a percentage off, an amount off, or free delivery.
create table discount_codes (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Z0-9_-]{3,30}$'),
  type text not null check (type in ('percent','amount','free_delivery')),
  value integer not null default 0,
  min_order integer not null default 0 check (min_order >= 0),
  max_uses integer check (max_uses is null or max_uses > 0),
  uses integer not null default 0 check (uses >= 0),
  expires_on date,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint discount_value_fits_type check (
    (type = 'percent' and value between 1 and 100) or (type = 'amount' and value > 0) or (type = 'free_delivery' and value = 0)
  )
);

-- Details a logged-in customer saved for checkout. Only ever changed by that customer.
-- Orders link to accounts by login, never by matching an email address, so nobody can
-- see someone else's orders by signing up with their email.
create table customer_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '' check (char_length(name) <= 80),
  phone text not null default '' check (char_length(phone) <= 20),
  city text not null default '' check (char_length(city) <= 60),
  address text not null default '' check (char_length(address) <= 300),
  updated_at timestamptz not null default now()
);

create table order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references orders(id) on delete cascade,
  product_id bigint references products(id) on delete set null, -- orders keep their own copy of name and price
  name text not null, brand text not null, price integer not null, qty integer not null
);
create index order_items_order_idx on order_items(order_id);
create index order_items_product_idx on order_items(product_id);

create table notifications (
  id bigint generated by default as identity primary key,
  type text not null, title text not null, body text not null,
  order_id bigint references orders(id) on delete cascade,
  read boolean not null default false,
  created_at timestamptz not null default now()
);

create table subscribers (email text primary key, created_at timestamptz not null default now());
create table order_attempts (ip_hash text not null, at timestamptz not null default now());
create index order_attempts_idx on order_attempts(ip_hash, at);
create table admins (user_id uuid primary key);

create table store_settings (
  id boolean primary key default true check (id), -- single row
  shipping_fee integer not null default 60,
  free_shipping_over integer not null default 1000,
  theme text not null default 'default' check (theme in ('default','newyear','halloween','ramadan','eid')),
  hero jsonb -- the home page's three hero boxes as set in the dashboard; empty means the built-in design
);
insert into store_settings default values;

-- Each brand's logo, shown in the home page's brands section. Brands without one show their name.
create table brand_logos (
  brand text primary key check (char_length(brand) between 2 and 60),
  logo text not null check (logo ~ '^https://[^\s"''<>()\\]+$'),
  updated_at timestamptz not null default now()
);

-- Themes booked for a set period. While one is running it overrides store_settings.theme,
-- and afterwards the store goes back to that theme by itself. Periods can't overlap.
create table theme_schedule (
  id bigint generated by default as identity primary key,
  theme text not null check (theme in ('default','newyear','halloween','ramadan','eid')),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  created_at timestamptz not null default now(),
  constraint schedule_ends_after_start check (ends_at > starts_at),
  constraint schedule_no_overlap exclude using gist (tstzrange(starts_at, ends_at) with &&)
);

-- ---------------------------------------------------------------- helpers
create function is_admin() returns boolean language sql stable security definer set search_path = public as
$$ select exists (select 1 from admins where user_id = auth.uid()) $$;

create function require_admin() returns void language plpgsql stable security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'Not authorised' using errcode = '42501'; end if;
end $$;

create function order_number(p_id bigint) returns text language sql immutable set search_path = public as
$$ select 'ALO-' || (10000 + p_id) $$;

create function order_json(o orders) returns jsonb language sql stable set search_path = public as
$$ select to_jsonb(o) || jsonb_build_object('number', order_number(o.id)) $$;

create function like_pattern(q text) returns text language sql immutable set search_path = public as
$$ select '%' || regexp_replace(q, '([%_\\])', '\\\1', 'g') || '%' $$;

-- Works out what a code does for an order, or says why it can't be used. Never trusts the browser's numbers.
create function apply_discount(p_code text, p_subtotal integer, p_shipping integer, p_lock boolean) returns jsonb language plpgsql security definer set search_path = public as $$
declare d discount_codes;
begin
  if p_lock then select * into d from discount_codes where code = p_code and active for update;
  else select * into d from discount_codes where code = p_code and active;
  end if;
  if not found then return jsonb_build_object('error', 'This code isn’t valid'); end if;
  if d.expires_on is not null and d.expires_on < (now() at time zone 'Africa/Cairo')::date then return jsonb_build_object('error', 'This code has expired'); end if;
  if d.max_uses is not null and d.uses >= d.max_uses then return jsonb_build_object('error', 'This code has reached its limit'); end if;
  if p_subtotal < d.min_order then return jsonb_build_object('error', 'Spend at least ' || to_char(d.min_order, 'FM999,999,990') || ' EGP to use this code'); end if;
  if d.type = 'free_delivery' and p_shipping = 0 then return jsonb_build_object('error', 'Your order already has free delivery'); end if;
  return jsonb_build_object('code', d.code, 'type', d.type, 'value', d.value,
    'discount', case d.type when 'percent' then round(p_subtotal * d.value / 100.0)::int when 'amount' then least(d.value, p_subtotal) else 0 end,
    'shipping', case when d.type = 'free_delivery' then 0 else p_shipping end);
end $$;

-- ---------------------------------------------------------------- public functions
create function place_order(payload jsonb) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_name text := left(btrim(coalesce(payload->>'name', '')), 80);
  v_phone text := left(btrim(coalesce(payload->>'phone', '')), 20);
  v_email text := lower(left(btrim(coalesce(payload->>'email', '')), 120));
  v_city text := left(btrim(coalesce(payload->>'city', '')), 60);
  v_address text := left(btrim(coalesce(payload->>'address', '')), 300);
  v_notes text := left(btrim(coalesce(payload->>'notes', '')), 500);
  v_fields jsonb := '{}';
  v_ip text;
  v_item jsonb;
  v_line record;
  v_product products;
  v_lines jsonb := '[]';
  v_subtotal integer := 0;
  v_count integer := 0;
  v_shipping integer;
  v_total integer;
  v_settings store_settings;
  v_customer bigint;
  v_order bigint;
  v_user uuid := auth.uid();
  v_code text := upper(btrim(coalesce(payload->>'code', '')));
  v_applied jsonb;
  v_discount integer := 0;
begin
  -- Logged-in orders always use the account's own email.
  if v_user is not null then select lower(email) into v_email from auth.users where id = v_user; end if;

  -- A simple per-visitor limit, so a script can't flood the store with orders.
  v_ip := md5(coalesce(split_part(nullif(current_setting('request.headers', true), '')::json->>'x-forwarded-for', ',', 1), 'unknown'));
  delete from order_attempts where at < now() - interval '1 minute';
  if (select count(*) from order_attempts where ip_hash = v_ip) >= 20 then
    raise exception 'Too many orders. Please wait a minute and try again.';
  end if;
  insert into order_attempts (ip_hash) values (v_ip);

  if char_length(v_name) < 2 then v_fields := v_fields || '{"name":"Please enter your full name"}'; end if;
  if v_phone !~ '^\+?[0-9][0-9 ()-]{6,18}$' then v_fields := v_fields || '{"phone":"Please enter a valid phone number"}'; end if;
  if v_email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' then v_fields := v_fields || '{"email":"Please enter a valid email"}'; end if;
  if char_length(v_city) < 2 then v_fields := v_fields || '{"city":"Please choose your governorate"}'; end if;
  if char_length(v_address) < 5 then v_fields := v_fields || '{"address":"Please enter your full address"}'; end if;
  if v_fields <> '{}' then raise exception 'Please check your details' using detail = v_fields::text; end if;

  if jsonb_typeof(payload->'items') <> 'array' or jsonb_array_length(payload->'items') not between 1 and 50 then
    raise exception 'Your cart is empty';
  end if;
  for v_item in select value from jsonb_array_elements(payload->'items') loop
    if coalesce(v_item->>'id', '') !~ '^[0-9]{1,15}$' or coalesce(v_item->>'qty', '') !~ '^[0-9]{1,2}$' or (v_item->>'qty')::int < 1 then
      raise exception 'Invalid item in cart';
    end if;
  end loop;

  -- Always the database's prices, never the browser's. Rows are locked so two
  -- customers can't both buy the last unit.
  for v_line in
    select (value->>'id')::bigint as id, sum((value->>'qty')::int)::int as qty
    from jsonb_array_elements(payload->'items') group by 1 order by 1
  loop
    select * into v_product from products where id = v_line.id and active for update;
    if not found then raise exception 'An item in your cart is no longer available'; end if;
    if v_product.stock < v_line.qty then
      if v_product.stock > 0 then raise exception 'Only % left of %', v_product.stock, v_product.name;
      else raise exception '% just sold out', v_product.name; end if;
    end if;
    v_subtotal := v_subtotal + v_product.price * v_line.qty;
    v_count := v_count + v_line.qty;
    v_lines := v_lines || jsonb_build_object('id', v_product.id, 'name', v_product.name, 'brand', v_product.brand, 'price', v_product.price, 'qty', v_line.qty);
    update products set stock = stock - v_line.qty where id = v_line.id;
  end loop;

  select * into v_settings from store_settings;
  v_shipping := case when v_subtotal >= v_settings.free_shipping_over then 0 else v_settings.shipping_fee end;

  -- The code is checked here, with the row locked, so its limit can't be passed by two orders at once.
  if v_code <> '' then
    v_applied := apply_discount(v_code, v_subtotal, v_shipping, true);
    if v_applied ? 'error' then raise exception '%', v_applied->>'error'; end if;
    v_discount := (v_applied->>'discount')::int;
    v_shipping := (v_applied->>'shipping')::int;
    update discount_codes set uses = uses + 1 where code = v_code;
  end if;
  v_total := v_subtotal - v_discount + v_shipping;

  insert into customers (name, email, phone, city, address) values (v_name, v_email, v_phone, v_city, v_address)
  on conflict (email) do update set name = excluded.name, phone = excluded.phone, city = excluded.city, address = excluded.address
  returning id into v_customer;

  insert into orders (customer_id, customer_name, email, phone, city, address, notes, subtotal, shipping, total, user_id, discount, discount_code)
  values (v_customer, v_name, v_email, v_phone, v_city, v_address, v_notes, v_subtotal, v_shipping, v_total, v_user, v_discount, nullif(v_code, ''))
  returning id into v_order;

  insert into order_items (order_id, product_id, name, brand, price, qty)
  select v_order, (l->>'id')::bigint, l->>'name', l->>'brand', (l->>'price')::int, (l->>'qty')::int from jsonb_array_elements(v_lines) l;

  -- The dashboard listens for new rows here through Supabase Realtime.
  insert into notifications (type, title, body, order_id)
  values ('order', 'New order ' || order_number(v_order),
    v_name || ' · ' || v_count || case when v_count = 1 then ' item' else ' items' end || ' · ' || to_char(v_total, 'FM999,999,990') || ' EGP', v_order);

  if v_user is not null and payload->>'save' = 'true' then
    insert into customer_profiles (user_id, name, phone, city, address) values (v_user, v_name, v_phone, v_city, v_address)
    on conflict (user_id) do update set name = excluded.name, phone = excluded.phone, city = excluded.city, address = excluded.address, updated_at = now();
  end if;

  return jsonb_build_object('number', order_number(v_order), 'total', v_total, 'subtotal', v_subtotal, 'shipping', v_shipping, 'discount', v_discount, 'discount_code', nullif(v_code, ''),
    'name', v_name, 'city', v_city, 'items', v_lines);
end $$;

-- Lets checkout show the discount before the order is placed. place_order checks it again.
create function preview_discount(p_code text, p_items jsonb) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_code text := upper(btrim(coalesce(p_code, '')));
  v_ip text := md5('code:' || coalesce(split_part(nullif(current_setting('request.headers', true), '')::json->>'x-forwarded-for', ',', 1), 'unknown'));
  v_settings store_settings;
  v_subtotal integer;
  v_shipping integer;
  v_applied jsonb;
begin
  -- A limit per visitor, so codes can't be guessed by trying thousands of them.
  delete from order_attempts where at < now() - interval '1 minute';
  if (select count(*) from order_attempts where ip_hash = v_ip) >= 30 then
    return jsonb_build_object('error', 'Too many attempts. Please wait a few minutes and try again.');
  end if;
  insert into order_attempts (ip_hash) values (v_ip);

  if jsonb_typeof(p_items) <> 'array' or exists (select 1 from jsonb_array_elements(p_items) i
      where coalesce(i->>'id', '') !~ '^[0-9]{1,15}$' or coalesce(i->>'qty', '') !~ '^[0-9]{1,2}$') then
    return jsonb_build_object('error', 'Invalid item in cart');
  end if;
  select coalesce(sum(p.price * (i->>'qty')::int), 0)::int into v_subtotal
    from jsonb_array_elements(p_items) i join products p on p.id = (i->>'id')::bigint and p.active;
  select * into v_settings from store_settings;
  v_shipping := case when v_subtotal >= v_settings.free_shipping_over then 0 else v_settings.shipping_fee end;
  v_applied := apply_discount(v_code, v_subtotal, v_shipping, false);
  if v_applied ? 'error' then return v_applied; end if;
  return v_applied || jsonb_build_object('subtotal', v_subtotal,
    'total', v_subtotal - (v_applied->>'discount')::int + (v_applied->>'shipping')::int);
end $$;

-- A logged-in customer's own orders, newest first.
create function my_orders() returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'number', order_number(o.id), 'created_at', o.created_at, 'status', o.status, 'city', o.city,
    'subtotal', o.subtotal, 'shipping', o.shipping, 'total', o.total, 'discount', o.discount, 'discount_code', o.discount_code,
    'items', (select jsonb_agg(jsonb_build_object('name', i.name, 'name_ar', p.name_ar, 'brand', i.brand, 'price', i.price, 'qty', i.qty) order by i.id) from order_items i left join products p on p.id = i.product_id where i.order_id = o.id)
  ) order by o.id desc), '[]')
  from (select * from orders where user_id = auth.uid() order by id desc limit 100) o
$$;

-- The theme visitors should see right now.
create function current_theme() returns text language sql stable security definer set search_path = public as $$
  select coalesce(
    (select theme from theme_schedule where now() >= starts_at and now() < ends_at limit 1),
    (select theme from store_settings limit 1)
  )
$$;

create function subscribe(p_email text) returns void language plpgsql security definer set search_path = public as $$
declare v_email text := lower(left(btrim(coalesce(p_email, '')), 120));
begin
  if v_email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' then raise exception 'Please enter a valid email'; end if;
  insert into subscribers (email) values (v_email) on conflict do nothing;
end $$;

-- ---------------------------------------------------------------- admin functions
create function admin_analytics() returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_today date := (now() at time zone 'Africa/Cairo')::date;
  v_month date := date_trunc('month', v_today)::date;
  v_last date := (v_month - interval '1 month')::date;
  v_last_same date := least(v_last + (extract(day from v_today)::int - 1), v_month - 1);
  v_avg numeric;
  t record; y record; m record; lm record;
begin
  perform require_admin();
  select coalesce(sum(total), 0) revenue, count(*) orders into t from orders where status <> 'cancelled' and local_day = v_today;
  select coalesce(sum(total), 0) revenue into y from orders where status <> 'cancelled' and local_day = v_today - 1;
  select coalesce(sum(total), 0) revenue, count(*) orders into m from orders where status <> 'cancelled' and local_day between v_month and v_today;
  select coalesce(sum(total), 0) revenue into lm from orders where status <> 'cancelled' and local_day between v_last and v_last_same;
  v_avg := case when m.orders > 0 then round(m.revenue::numeric / m.orders) else 0 end;

  return jsonb_build_object(
    'today', jsonb_build_object('revenue', t.revenue, 'orders', t.orders, 'yesterdayRevenue', y.revenue),
    'month', jsonb_build_object('revenue', m.revenue, 'orders', m.orders, 'lastMonthSamePeriod', lm.revenue, 'aov', v_avg),
    'clients', jsonb_build_object('total', (select count(*) from customers), 'newThisMonth', (select count(*) from customers where local_day >= v_month)),
    'daily', (select jsonb_agg(jsonb_build_object('key', to_char(d, 'YYYY-MM-DD'), 'revenue', coalesce(r.revenue, 0), 'orders', coalesce(r.orders, 0)) order by d)
      from generate_series(v_today - 89, v_today, interval '1 day') d
      left join (select local_day, sum(total) revenue, count(*) orders from orders where status <> 'cancelled' group by 1) r on r.local_day = d::date),
    'monthly', (select jsonb_agg(jsonb_build_object('key', to_char(d, 'YYYY-MM'), 'revenue', coalesce(r.revenue, 0), 'orders', coalesce(r.orders, 0)) order by d)
      from generate_series(v_month - interval '11 months', v_month, interval '1 month') d
      left join (select date_trunc('month', local_day::timestamp) mth, sum(total) revenue, count(*) orders from orders where status <> 'cancelled' group by 1) r on r.mth = d),
    'statusCounts', (select jsonb_object_agg(s, (select count(*) from orders o where o.status = s)) from unnest(array['pending','confirmed','shipped','delivered','cancelled']) s),
    'topProducts', coalesce((select jsonb_agg(x order by x.revenue desc) from (
      select i.name, i.brand, sum(i.qty) qty, sum(i.qty * i.price) revenue from order_items i join orders o on o.id = i.order_id
      where o.status <> 'cancelled' and o.local_day >= v_today - 29 group by i.name, i.brand order by 4 desc limit 5) x), '[]'),
    'lowStock', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'stock', stock) order by stock) from products where active and stock <= 10), '[]'),
    'recentOrders', coalesce((select jsonb_agg(order_json(o) order by o.id desc) from (select * from orders order by id desc limit 6) o), '[]')
  );
end $$;

create function admin_set_theme(p_theme text) returns text language plpgsql security definer set search_path = public as $$
begin
  perform require_admin();
  if p_theme not in ('default','newyear','halloween','ramadan','eid') then raise exception 'Unknown theme'; end if;
  update store_settings set theme = p_theme where id; -- Supabase refuses updates without a where clause
  return p_theme;
end $$;

-- Cleans one hero box from the dashboard: only known fields, length limits, and links,
-- pictures and colours in a safe form, since every visitor's browser shows them.
-- A link is a full https:// address or a page of this store, like shop.html or #reviews. Nothing else, so no javascript: links.
create function hero_link(v text) returns text language plpgsql immutable set search_path = public as $$
begin
  v := btrim(coalesce(v, ''));
  if v <> '' and not (v ~ '^https://[^\s"''<>\\]+$' or (v ~ '^[A-Za-z0-9_#?./][A-Za-z0-9_./?=&%#+-]*$' and v !~ '^//')) then
    raise exception 'Links must start with https:// or be a page of this store, like shop.html';
  end if;
  return v;
end $$;

create function hero_image(v text) returns text language plpgsql immutable set search_path = public as $$
begin
  v := btrim(coalesce(v, ''));
  if v <> '' and v !~ '^https://[^\s"''<>()\\]+$' then raise exception 'That picture address isn’t valid'; end if;
  return v;
end $$;

create function hero_box(b jsonb, keys text[], lims integer[]) returns jsonb language plpgsql immutable set search_path = public as $$
declare
  o jsonb := '{}';
  v text;
  s jsonb;
  v_slides jsonb := '[]';
begin
  for i in 1 .. array_length(keys, 1) loop
    v := btrim(coalesce(b->>keys[i], ''));
    if char_length(v) > lims[i] then raise exception 'Some text is too long (% characters at most)', lims[i]; end if;
    if keys[i] like '%link' then v := hero_link(v); end if;
    o := o || jsonb_build_object(keys[i], v);
  end loop;
  o := o || jsonb_build_object('image', hero_image(b->>'image'));
  v := coalesce(b->>'image_mode', 'art');
  o := o || jsonb_build_object('image_mode', case when v in ('art', 'cover') then v else 'art' end);
  v := lower(btrim(coalesce(b->>'bg', '')));
  if v <> '' and v !~ '^#[0-9a-f]{6}$' then raise exception 'Colours must look like #66794a'; end if;
  o := o || jsonb_build_object('bg', v);
  -- Banner mode: the box shows only designed pictures (an ad slideshow), each with an optional Arabic version and link.
  if jsonb_typeof(b->'slides') = 'array' then
    if jsonb_array_length(b->'slides') > 8 then raise exception 'A box can have 8 banners at most'; end if;
    for s in select value from jsonb_array_elements(b->'slides') loop
      if jsonb_typeof(s) <> 'object' or hero_image(s->>'image') = '' then raise exception 'Every banner needs a picture'; end if;
      if char_length(btrim(coalesce(s->>'alt', ''))) > 120 then raise exception 'Banner descriptions can be 120 characters at most'; end if;
      v_slides := v_slides || jsonb_build_array(jsonb_build_object('image', hero_image(s->>'image'), 'image_ar', hero_image(s->>'image_ar'),
        'link', hero_link(s->>'link'), 'alt', btrim(coalesce(s->>'alt', ''))));
    end loop;
  end if;
  v := case when b->>'mode' = 'banner' then 'banner' else 'text' end;
  if v = 'banner' and jsonb_array_length(v_slides) = 0 then raise exception 'Add at least one banner picture, or switch the box back to text'; end if;
  return o || jsonb_build_object('mode', v, 'slides', v_slides);
end $$;

-- Saves the home page hero from the dashboard. Null puts the built-in design back.
create function admin_set_hero(p_hero jsonb) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_main constant text[] := array['eyebrow','eyebrow_ar','line1','line1_ar','line2','line2_ar','text','text_ar','btn1_label','btn1_label_ar','btn1_link','btn2_label','btn2_label_ar','btn2_link'];
  v_main_lim constant integer[] := array[40,40,24,24,24,24,220,220,30,30,300,30,30,300];
  v_side constant text[] := array['title','title_ar','text','text_ar','link'];
  v_side_lim constant integer[] := array[16,16,80,80,300];
  v_box jsonb;
  v_out jsonb;
begin
  perform require_admin();
  if p_hero is null or jsonb_typeof(p_hero) = 'null' then
    update store_settings set hero = null where id;
    return null;
  end if;
  if jsonb_typeof(p_hero) <> 'object' then raise exception 'Invalid home page content'; end if;
  foreach v_box in array array[coalesce(p_hero->'main', '{}'), coalesce(p_hero->'t2', '{}'), coalesce(p_hero->'t3', '{}')] loop
    if jsonb_typeof(v_box) <> 'object' then raise exception 'Invalid home page content'; end if;
  end loop;
  v_out := jsonb_build_object(
    'main', hero_box(coalesce(p_hero->'main', '{}'), v_main, v_main_lim),
    't2', hero_box(coalesce(p_hero->'t2', '{}'), v_side, v_side_lim),
    't3', hero_box(coalesce(p_hero->'t3', '{}'), v_side, v_side_lim));
  update store_settings set hero = v_out where id;
  return v_out;
end $$;

-- Updates prices and stock from the shop's own item sheet, matching rows by product code.
-- Each row is {code, price, stock}; a missing price or stock leaves that value as it is.
-- Prices are rounded to whole pounds. Returns how many products changed.
create function admin_import_sheet(p_rows jsonb) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_updated integer;
begin
  perform require_admin();
  if jsonb_typeof(p_rows) is distinct from 'array' or jsonb_array_length(p_rows) = 0 then raise exception 'The sheet has no rows'; end if;
  if jsonb_array_length(p_rows) > 20000 then raise exception 'The sheet is too large (20,000 rows at most)'; end if;
  with s as (
    select distinct on (btrim(code)) btrim(code) code, price, stock
    from jsonb_to_recordset(p_rows) as x(code text, price numeric, stock numeric)
    where nullif(btrim(code), '') is not null
    order by btrim(code)
  ), n as (
    select p.id,
      coalesce(case when s.price >= 1 and s.price <= 1000000 then round(s.price)::integer end, p.price) np,
      coalesce(case when s.stock is not null and s.stock <= 1000000 then greatest(floor(s.stock), 0)::integer end, p.stock) ns
    from products p join s on s.code = p.code
  ), upd as (
    update products p set price = n.np, stock = n.ns,
      compare_at = case when p.compare_at > n.np then p.compare_at end -- a sale price that is no longer below the original is dropped
    from n where p.id = n.id and (p.price <> n.np or p.stock <> n.ns)
    returning p.id
  )
  select count(*) into v_updated from upd;
  return jsonb_build_object('updated', v_updated);
end $$;

-- Times come in as Cairo local time, whatever timezone the admin's computer is set to.
create function admin_add_theme_schedule(p_theme text, p_starts text, p_ends text) returns void language plpgsql security definer set search_path = public as $$
declare
  v_starts timestamptz;
  v_ends timestamptz;
begin
  perform require_admin();
  if p_theme not in ('default','newyear','halloween','ramadan','eid') then raise exception 'Unknown theme'; end if;
  begin
    v_starts := p_starts::timestamp at time zone 'Africa/Cairo';
    v_ends := p_ends::timestamp at time zone 'Africa/Cairo';
  exception when others then raise exception 'Please enter a valid start and end time';
  end;
  if v_ends <= v_starts then raise exception 'The end must be after the start'; end if;
  if v_ends <= now() then raise exception 'The end time has already passed'; end if;
  insert into theme_schedule (theme, starts_at, ends_at) values (p_theme, v_starts, v_ends);
exception when exclusion_violation then
  raise exception 'That overlaps another scheduled theme. Change the dates or delete the other one first.';
end $$;

create function admin_list_products() returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform require_admin();
  return coalesce((select jsonb_agg(to_jsonb(p) || jsonb_build_object('sold', coalesce((
      select sum(i.qty) from order_items i join orders o on o.id = i.order_id where i.product_id = p.id and o.status <> 'cancelled'), 0)) order by p.id desc)
    from products p), '[]');
end $$;

create function admin_list_orders(p_q text default '', p_status text default '', p_page integer default 1) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_size constant integer := 20;
  v_q text := left(btrim(coalesce(p_q, '')), 80);
  v_like text := like_pattern(v_q);
  v_num bigint := null;
  v_digits text;
  v_total bigint;
  v_rows jsonb;
begin
  perform require_admin();
  v_digits := (regexp_match(v_q, '^(?:alo-?)?([0-9]{1,15})$', 'i'))[1];
  if v_digits is not null then
    v_num := v_digits::bigint - case when char_length(v_digits) >= 5 then 10000 else 0 end;
  end if;

  select count(*) into v_total from orders o
  where (coalesce(p_status, '') = '' or o.status = p_status)
    and (v_q = '' or o.customer_name ilike v_like or o.email ilike v_like or o.phone ilike v_like or o.id = v_num);

  select coalesce(jsonb_agg(order_json(o) || jsonb_build_object('item_count', (select sum(qty) from order_items where order_id = o.id)) order by o.id desc), '[]') into v_rows
  from (select * from orders o
    where (coalesce(p_status, '') = '' or o.status = p_status)
      and (v_q = '' or o.customer_name ilike v_like or o.email ilike v_like or o.phone ilike v_like or o.id = v_num)
    order by o.id desc limit v_size offset (greatest(p_page, 1) - 1) * v_size) o;

  return jsonb_build_object('total', v_total, 'page', greatest(p_page, 1), 'size', v_size, 'rows', v_rows);
end $$;

create function admin_get_order(p_id bigint) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare o orders;
begin
  perform require_admin();
  select * into o from orders where id = p_id;
  if not found then raise exception 'Order not found'; end if;
  return order_json(o) || jsonb_build_object('items', (select jsonb_agg(jsonb_build_object('product_id', i.product_id, 'code', p.code, 'name', i.name, 'brand', i.brand, 'price', i.price, 'qty', i.qty) order by i.id) from order_items i left join products p on p.id = i.product_id where i.order_id = p_id));
end $$;

create function admin_set_order_status(p_id bigint, p_status text) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  o orders;
  it record;
begin
  perform require_admin();
  if p_status not in ('pending','confirmed','shipped','delivered','cancelled') then raise exception 'Invalid status'; end if;
  select * into o from orders where id = p_id for update;
  if not found then raise exception 'Order not found'; end if;
  if o.status <> p_status then
    -- A cancelled order gives its use of a discount code back; reopening takes it again.
    if o.discount_code is not null and p_status = 'cancelled' then
      update discount_codes set uses = greatest(uses - 1, 0) where code = o.discount_code;
    elsif o.discount_code is not null and o.status = 'cancelled' then
      update discount_codes set uses = uses + 1 where code = o.discount_code;
    end if;
    -- Cancelling puts the items back on the shelf; reopening takes them again.
    for it in select i.product_id, i.qty, i.name from order_items i where i.order_id = p_id and i.product_id is not null order by i.product_id loop
      if p_status = 'cancelled' then
        update products set stock = stock + it.qty where id = it.product_id;
      elsif o.status = 'cancelled' then
        update products set stock = stock - it.qty where id = it.product_id and stock >= it.qty;
        if not found then raise exception 'Not enough stock of % to reopen this order', it.name; end if;
      end if;
    end loop;
    update orders set status = p_status where id = p_id;
  end if;
  return admin_get_order(p_id);
end $$;

create function admin_list_customers(p_q text default '', p_sort text default 'recent', p_page integer default 1) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_size constant integer := 20;
  v_q text := left(btrim(coalesce(p_q, '')), 80);
  v_like text := like_pattern(v_q);
  v_total bigint;
  v_rows jsonb;
begin
  perform require_admin();
  select count(*) into v_total from customers c
  where v_q = '' or c.name ilike v_like or c.email ilike v_like or c.phone ilike v_like or c.city ilike v_like;

  select coalesce(jsonb_agg(to_jsonb(x)), '[]') into v_rows from (
    select c.*, count(o.id) filter (where o.status <> 'cancelled') order_count,
      coalesce(sum(o.total) filter (where o.status <> 'cancelled'), 0) total_spent, max(o.created_at) last_order
    from customers c left join orders o on o.customer_id = c.id
    where v_q = '' or c.name ilike v_like or c.email ilike v_like or c.phone ilike v_like or c.city ilike v_like
    group by c.id
    order by
      case when p_sort = 'spent' then coalesce(sum(o.total) filter (where o.status <> 'cancelled'), 0) end desc nulls last,
      case when p_sort = 'orders' then count(o.id) filter (where o.status <> 'cancelled') end desc nulls last,
      case when p_sort = 'name' then lower(c.name) end asc nulls last,
      max(o.created_at) desc nulls last, c.id desc
    limit v_size offset (greatest(p_page, 1) - 1) * v_size) x;

  return jsonb_build_object('total', v_total, 'page', greatest(p_page, 1), 'size', v_size, 'rows', v_rows);
end $$;

create function admin_get_customer(p_id bigint) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare c record;
begin
  perform require_admin();
  select cu.*, count(o.id) filter (where o.status <> 'cancelled') order_count,
    coalesce(sum(o.total) filter (where o.status <> 'cancelled'), 0) total_spent, max(o.created_at) last_order
  into c from customers cu left join orders o on o.customer_id = cu.id where cu.id = p_id group by cu.id;
  if not found then raise exception 'Customer not found'; end if;
  return to_jsonb(c) || jsonb_build_object('orders', coalesce((select jsonb_agg(order_json(o) || jsonb_build_object('item_count', (select sum(qty) from order_items where order_id = o.id)) order by o.id desc) from orders o where o.customer_id = p_id), '[]'));
end $$;

